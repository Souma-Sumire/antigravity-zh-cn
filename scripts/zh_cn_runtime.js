  const PERIOD_MAP = {
    'weekly': '本周',
    '5-hour': '5 小时',
    'five-hour': '5 小时',
    'five hour': '5 小时',
    'daily': '今日',
    'monthly': '本月',
    'hourly': '本小时'
  };

  function translateDuration(s) {
    return s
      .replace(/(\d+)\s*weeks?/gi, '$1 周')
      .replace(/(\d+)\s*days?/gi, '$1 天')
      .replace(/(\d+)\s*hours?/gi, '$1 小时')
      .replace(/(\d+)\s*minutes?/gi, '$1 分钟')
      .replace(/(\d+)\s*mins?/gi, '$1 分钟')
      .replace(/(\d+)\s*seconds?/gi, '$1 秒')
      .replace(/(\d+)\s*secs?/gi, '$1 秒')
      .replace(/\s*,\s*/g, ' ')
      .replace(/\s+and\s+/gi, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function getCustomDict() {
    try {
      const raw = window.localStorage.getItem('antigravity.ui.customDict');
      if (raw) {
        const parsed = JSON.parse(raw);
        if (parsed && typeof parsed === 'object') return parsed;
      }
    } catch (_) {}
    return {};
  }

  let customDict = getCustomDict();

  function translateText(str) {
    if (!str || typeof str !== 'string') return null;
    const trimmed = str.trim();
    if (!trimmed) return null;

    if (trimmed === 'when working') {
      return '（';
    }

    if (customDict[trimmed]) {
      return str.replace(trimmed, customDict[trimmed]);
    }
    if (EXACT_MAP[trimmed]) {
      return str.replace(trimmed, EXACT_MAP[trimmed]);
    }
    const normalizedKey = trimmed.replace(/\s+/g, ' ');
    if (EXACT_MAP[normalizedKey]) {
      return str.replace(trimmed, EXACT_MAP[normalizedKey]);
    }

const notApplyMatch = normalizedKey.match(
      /^You have (?:hit|reached|exhausted|used all of) your (weekly|5-hour|five-hour|five hour|daily|monthly|hourly) limit,\s*so the (weekly|5-hour|five-hour|five hour|daily|monthly|hourly) limit does not currently apply\.\s*Your \1 limit will refresh in (.+?)\.?$/i
    );
    if (notApplyMatch) {
      const p1 = PERIOD_MAP[notApplyMatch[1].toLowerCase()] || notApplyMatch[1];
      const p2 = PERIOD_MAP[notApplyMatch[2].toLowerCase()] || notApplyMatch[2];
      const dur = translateDuration(notApplyMatch[3]);
      return str.replace(trimmed, `您已达到 ${p1} 额度上限，因此当前不适用${p2}额度。您的 ${p1} 额度将在 ${dur} 后刷新。`);
    }

    const paidPlanMatch = normalizedKey.match(
      /^You have (?:hit|reached|exhausted|used all of) your (weekly|5-hour|five-hour|five hour|daily|monthly|hourly) limit,\s*it will (?:fully )?refresh in (.+?)\.\s*If on a supported paid plan, you can use AI credits in the interim\.?$/i
    );
    if (paidPlanMatch) {
      const p1 = PERIOD_MAP[paidPlanMatch[1].toLowerCase()] || paidPlanMatch[1];
      const dur = translateDuration(paidPlanMatch[2]);
      return str.replace(trimmed, `您已达到 ${p1} 额度上限，将在 ${dur} 后刷新。若使用受支持的付费订阅方案，期间可以使用 AI 点数继续调用。`);
    }

    const usedSomeMatch = normalizedKey.match(
      /^You have used some of your (weekly|5-hour|five-hour|five hour|daily|monthly|hourly) limit,\s*it will (?:fully )?refresh in (.+?)\.?$/i
    );
    if (usedSomeMatch) {
      const period = PERIOD_MAP[usedSomeMatch[1].toLowerCase()] || usedSomeMatch[1];
      const dur = translateDuration(usedSomeMatch[2]);
      return str.replace(trimmed, `您已使用部分${period}额度，将于 ${dur}后完全重置。`);
    }

    const reachedLimitMatch = normalizedKey.match(
      /^You have (?:hit|reached|exhausted|used all of) your (weekly|5-hour|five-hour|five hour|daily|monthly|hourly) limit,\s*it will (?:fully )?refresh in (.+?)\.?$/i
    );
    if (reachedLimitMatch) {
      const period = PERIOD_MAP[reachedLimitMatch[1].toLowerCase()] || reachedLimitMatch[1];
      const dur = translateDuration(reachedLimitMatch[2]);
      return str.replace(trimmed, `您的${period}额度已用尽，将于 ${dur}后重置。`);
    }

    const unusedLimitMatch = normalizedKey.match(
      /^You have not used any of your (weekly|5-hour|five-hour|five hour|daily|monthly|hourly) limit\.?$/i
    );
    if (unusedLimitMatch) {
      const period = PERIOD_MAP[unusedLimitMatch[1].toLowerCase()] || unusedLimitMatch[1];
      return str.replace(trimmed, `您尚未使用${period}额度。`);
    }

    const resetsInMatch = normalizedKey.match(/^(?:Resets|Refreshes|Will refresh) in (.+?)\.?$/i);
    if (resetsInMatch) {
      const dur = translateDuration(resetsInMatch[1]);
      return str.replace(trimmed, `将于 ${dur}后重置`);
    }

    for (let i = 0; i < REGEX_RULES.length; i++) {
      const [re, replacement] = REGEX_RULES[i];
      if (re.test(normalizedKey)) {
        return str.replace(trimmed, normalizedKey.replace(re, replacement));
      }
    }
    return null;
  }

  const SKIP_TAGS = new Set([
    'PRE', 'CODE', 'SCRIPT', 'STYLE', 'TEXTAREA', 'SVG', 'MATH', 'NOSCRIPT', 'CANVAS'
  ]);

  const SKIP_CLOSEST_SELECTOR = [
    'pre',
    'code',
    '.monaco-editor',
    '.xterm',
    '.katex',
    '[data-lexical-editor="true"]',
    '[contenteditable="true"]',
    '[data-markdown-root]',
    '[data-testid="user-message-bubble"]',
    '[data-testid="user-input-step"]',
    '[data-quotable="true"]',
    '#agy-zh-cn-toggle-bar'
  ].join(', ');

  function shouldSkipElement(el) {
    if (!el || el.nodeType !== 1) return true;
    if (SKIP_TAGS.has(el.tagName)) return true;
    if (el.id === 'agy-zh-cn-toggle-bar') return true;
    if (
      el.isContentEditable ||
      el.getAttribute('contenteditable') === 'true' ||
      el.getAttribute('data-lexical-editor') === 'true' ||
      el.hasAttribute('data-markdown-root') ||
      el.getAttribute('data-quotable') === 'true'
    ) {
      return true;
    }
    if (el.closest && el.closest(SKIP_CLOSEST_SELECTOR)) {
      return true;
    }
    const cls = typeof el.className === 'string' ? el.className : '';
    if (
      cls.includes('material-symbols') ||
      cls.includes('material-icons') ||
      cls.includes('codicon') ||
      el.getAttribute('translate') === 'no'
    ) {
      return true;
    }
    return false;
  }

  const ATTR_LIST = ['placeholder', 'title', 'aria-label'];

  function processTextNode(node) {
    const parent = node.parentElement;
    if (!parent || shouldSkipElement(parent)) return;

    const currentVal = node.nodeValue;
    if (!currentVal || !currentVal.trim()) return;

    if (currentLang === 'zh-CN') {
      let record = state.nodeMap.get(node);
      if (record) {
        // 如果当前值与上次翻译值相同，说明外部未变更，无需重复处理
        if (currentVal === record.translated) {
          return;
        }
        // 如果当前值与上次翻译值不同，说明外部（如 React 切换 option/状态变更）修改了文本
        // 此时新的文本即为新的原始输入
        record.orig = currentVal;
      } else {
        record = { orig: currentVal, translated: null };
        state.nodeMap.set(node, record);
      }

      const translated = translateText(record.orig);
      if (translated && translated !== currentVal) {
        record.translated = translated;
        state.translatedNodes.add(node);
        node.nodeValue = translated;
      } else {
        record.translated = currentVal;
      }
    } else {
      const record = state.nodeMap.get(node);
      if (record && record.orig && node.nodeValue !== record.orig) {
        node.nodeValue = record.orig;
      }
    }
  }

  function processAttributes(el) {
    if (!el || el.nodeType !== 1 || el.id === 'agy-zh-cn-toggle-bar') return;
    for (let i = 0; i < ATTR_LIST.length; i++) {
      const attr = ATTR_LIST[i];
      const val = el.getAttribute(attr);
      if (!val) continue;

      let elRecord = state.attrMap.get(el);
      if (!elRecord) {
        elRecord = {};
        state.attrMap.set(el, elRecord);
      }

      if (currentLang === 'zh-CN') {
        let attrInfo = elRecord[attr];
        if (attrInfo) {
          if (val === attrInfo.translated) {
            continue;
          }
          attrInfo.orig = val;
        } else {
          attrInfo = { orig: val, translated: null };
          elRecord[attr] = attrInfo;
        }

        const translated = translateText(attrInfo.orig);
        if (translated && translated !== val) {
          attrInfo.translated = translated;
          state.translatedAttrElements.add(el);
          el.setAttribute(attr, translated);
        } else {
          attrInfo.translated = val;
        }
      } else {
        const attrInfo = elRecord[attr];
        if (attrInfo && attrInfo.orig && el.getAttribute(attr) !== attrInfo.orig) {
          el.setAttribute(attr, attrInfo.orig);
        }
      }
    }
  }

  function walkAndTranslate(root) {
    if (!root) return;
    if (root.nodeType === 3) {
      processTextNode(root);
      return;
    }
    if (root.nodeType !== 1 && root.nodeType !== 9 && root.nodeType !== 11) return;
    if (root.nodeType === 1) {
      processAttributes(root);
      if (shouldSkipElement(root)) return;
    }

    const walker = document.createTreeWalker(
      root,
      NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
      null
    );

    let curr = walker.nextNode();
    while (curr) {
      if (curr.nodeType === 3) {
        processTextNode(curr);
      } else if (curr.nodeType === 1) {
        processAttributes(curr);
      }
      curr = walker.nextNode();
    }
  }

  function restoreAllToEnglish() {
    state.translatedNodes.forEach((node) => {
      const record = state.nodeMap.get(node);
      if (record && record.orig) {
        node.nodeValue = record.orig;
      }
    });
    state.translatedAttrElements.forEach((el) => {
      const elRecord = state.attrMap.get(el);
      if (elRecord) {
        for (const attr of ATTR_LIST) {
          if (elRecord[attr] && elRecord[attr].orig) {
            el.setAttribute(attr, elRecord[attr].orig);
          }
        }
      }
    });
  }

  let pendingNodes = new Set();
  let rafScheduled = false;

  function flushPending() {
    rafScheduled = false;
    if (currentLang !== 'zh-CN') {
      pendingNodes.clear();
      return;
    }
    const batch = Array.from(pendingNodes);
    pendingNodes.clear();
    for (let i = 0; i < batch.length; i++) {
      walkAndTranslate(batch[i]);
    }
  }

  function scheduleWalk(node) {
    if (!node) return;
    pendingNodes.add(node);
    if (!rafScheduled) {
      rafScheduled = true;
      window.requestAnimationFrame(flushPending);
    }
  }

