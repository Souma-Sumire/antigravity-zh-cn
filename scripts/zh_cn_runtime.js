  function setLanguage(lang) {
    currentLang = lang === 'en-US' ? 'en-US' : 'zh-CN';
    try {
      window.localStorage.setItem(STORAGE_KEY, currentLang);
    } catch (_) {}
    document.documentElement.lang = currentLang;
    if (currentLang === 'zh-CN') {
      customDict = getCustomDict();
      walkAndTranslate(document.body);
    } else {
      restoreAllToEnglish();
    }
    updateToggleBadge();
  }

  window.__AGY_I18N__ = {
    version: '1.1.0',
    getLanguage: () => currentLang,
    setLanguage,
    toggle: () => setLanguage(currentLang === 'zh-CN' ? 'en-US' : 'zh-CN'),
    apply: () => {
      customDict = getCustomDict();
      if (currentLang === 'zh-CN') {
        walkAndTranslate(document.body);
      }
      mountToggleBadge();
      updateToggleBadge();
    },
    addCustomEntries: (entries) => {
      if (!entries || typeof entries !== 'object') return;
      const merged = Object.assign({}, getCustomDict(), entries);
      try {
        window.localStorage.setItem('antigravity.ui.customDict', JSON.stringify(merged));
      } catch (_) {}
      customDict = merged;
      if (currentLang === 'zh-CN') {
        walkAndTranslate(document.body);
      }
    },
    getStats: () => ({
      language: currentLang,
      builtInEntries: Object.keys(EXACT_MAP).length,
      regexRules: REGEX_RULES.length,
      customEntries: Object.keys(customDict).length,
      translatedTextNodes: state.translatedNodes.size
    })
  };

  function startObserver() {
    if (!document.body) {
      window.addEventListener('DOMContentLoaded', startObserver, { once: true });
      return;
    }
    document.documentElement.lang = currentLang;
    mountToggleBadge();
    if (currentLang === 'zh-CN') {
      walkAndTranslate(document.body);
    }

    const observer = new MutationObserver((mutations) => {
      if (currentLang !== 'zh-CN') return;
      for (let i = 0; i < mutations.length; i++) {
        const m = mutations[i];
        if (m.type === 'childList') {
          for (let j = 0; j < m.addedNodes.length; j++) {
            scheduleWalk(m.addedNodes[j]);
          }
        } else if (m.type === 'characterData') {
          scheduleWalk(m.target);
        } else if (m.type === 'attributes') {
          processAttributes(m.target);
        }
      }
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ATTR_LIST
    });
    state.observer = observer;
  }

  startObserver();
